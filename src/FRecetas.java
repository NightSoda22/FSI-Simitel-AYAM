// Llena un combo usando solo entablar de Conexion2, con una tabla temporal que no se ve en pantalla

    private void llenarCombo(String consulta, javax.swing.JComboBox<String> combo) {
        JTable tablaTemporal = new JTable();
        cnx.entablar(consulta, tablaTemporal);
        combo.removeAllItems();
        for (int fila = 0; fila < tablaTemporal.getRowCount(); fila++) {
            combo.addItem(tablaTemporal.getValueAt(fila, 0).toString());
        }
    }

// Devuelve true si el SELECT encuentra al menos un registro
    private boolean existeRegistro(String consulta) {
        JTable tablaTemporal = new JTable();
        cnx.entablar(consulta, tablaTemporal);
        return tablaTemporal.getRowCount() > 0;
    }
