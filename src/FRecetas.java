    private void BInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BInsertarActionPerformed
        try {
            int numeroReceta = Integer.parseInt(TNumero.getText());
            String mensajeFinal = "";

            // 1. Si la receta no existe, se crea
            boolean recetaExiste = existeRegistro("SELECT 1 FROM recetas WHERE numero = " + numeroReceta);
            if (!recetaExiste) {
                Object[] resultadoReceta = cnx.ejecutarCRUD(
                        "gestionar_receta",
                        new Object[]{
                            "INSERT",
                            numeroReceta,
                            java.sql.Timestamp.valueOf(TFecha.getText()),
                            java.sql.Date.valueOf(TVigencia.getText()),
                            CBEstado.getSelectedItem().toString(),
                            Integer.parseInt(CBFolio.getSelectedItem().toString())
                        }
                );
                mensajeFinal = "Receta: " + resultadoReceta[1];
                if (Integer.parseInt(resultadoReceta[0].toString()) != 1) {
                    JOptionPane.showMessageDialog(this, mensajeFinal);
                    return;
                }
            } else {
                mensajeFinal = "La receta ya existía, solo se agrega el medicamento.";
            }

            // 2. Si hay un medicamento elegido, se agrega su detalle
            if (CBClaveMedicamento.getSelectedIndex() != -1) {
                Object[] resultadoDetalle = cnx.ejecutarCRUD(
                        "gestionar_detalle_receta",
                        new Object[]{
                            "INSERT",
                            CBClaveMedicamento.getSelectedItem().toString(),
                            numeroReceta,
                            TDosis.getText(),
                            TFrecuencia.getText(),
                            TDuracion.getText(),
                            TObservaciones.getText()
                        }
                );
                mensajeFinal = mensajeFinal + "\nDetalle: " + resultadoDetalle[1];
            }

            JOptionPane.showMessageDialog(this, mensajeFinal);
            cnx.entablar(todo, TDetallesRecetas);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, "Revise los datos: el número debe ser entero, la fecha como 2026-12-31 10:30:00 y la vigencia como 2026-12-31");
        }
    }//GEN-LAST:event_BInsertarActionPerformed

    private void TDetallesRecetasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TDetallesRecetasMouseClicked
        int filaSeleccionada = TDetallesRecetas.getSelectedRow();

        // La fecha se arregla para que siempre quede como 2026-10-05 09:30:00
        String fechaTexto = TDetallesRecetas.getValueAt(filaSeleccionada, 1).toString().replace("T", " ");
        if (fechaTexto.length() == 16) {
            fechaTexto = fechaTexto + ":00";
        }

        TNumero.setText(TDetallesRecetas.getValueAt(filaSeleccionada, 0).toString());
        TFecha.setText(fechaTexto);
        TVigencia.setText(TDetallesRecetas.getValueAt(filaSeleccionada, 2).toString());
        CBEstado.setSelectedItem(TDetallesRecetas.getValueAt(filaSeleccionada, 3).toString());
        CBFolio.setSelectedItem(TDetallesRecetas.getValueAt(filaSeleccionada, 4).toString());

        if (TDetallesRecetas.getValueAt(filaSeleccionada, 5) == null) {
            // La receta no tiene medicamento: se limpian los campos del detalle
            CBClaveMedicamento.setSelectedIndex(-1);
            TDosis.setText("");
            TFrecuencia.setText("");
            TDuracion.setText("");
            TObservaciones.setText("");
        } else {
            CBClaveMedicamento.setSelectedItem(TDetallesRecetas.getValueAt(filaSeleccionada, 5).toString());
            TDosis.setText(TDetallesRecetas.getValueAt(filaSeleccionada, 6).toString());
            TFrecuencia.setText(TDetallesRecetas.getValueAt(filaSeleccionada, 7).toString());
            TDuracion.setText(TDetallesRecetas.getValueAt(filaSeleccionada, 8).toString());
            TObservaciones.setText(TDetallesRecetas.getValueAt(filaSeleccionada, 9).toString());
        }
    }//GEN-LAST:event_TDetallesRecetasMouseClicked

    private void BActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BActualizarActionPerformed
        try {
            int numeroReceta = Integer.parseInt(TNumero.getText());

            // 1. Se actualiza la receta
            Object[] resultadoReceta = cnx.ejecutarCRUD(
                    "gestionar_receta",
                    new Object[]{
                        "UPDATE",
                        numeroReceta,
                        java.sql.Timestamp.valueOf(TFecha.getText()),
                        java.sql.Date.valueOf(TVigencia.getText()),
                        CBEstado.getSelectedItem().toString(),
                        Integer.parseInt(CBFolio.getSelectedItem().toString())
                    }
            );
            String mensajeFinal = "Receta: " + resultadoReceta[1];

            // 2. Si hay un medicamento elegido, se actualiza su detalle
            if (CBClaveMedicamento.getSelectedIndex() != -1) {
                String claveMedicamento = CBClaveMedicamento.getSelectedItem().toString();
                boolean detalleExiste = existeRegistro(
                        "SELECT 1 FROM detalles_recetas WHERE recetas_numero = " + numeroReceta
                        + " AND medicamentos_claveme = '" + claveMedicamento + "'");

                String accionDetalle = "UPDATE";
                if (!detalleExiste) {
                    accionDetalle = "INSERT";
                }

                Object[] resultadoDetalle = cnx.ejecutarCRUD(
                        "gestionar_detalle_receta",
                        new Object[]{
                            accionDetalle,
                            claveMedicamento,
                            numeroReceta,
                            TDosis.getText(),
                            TFrecuencia.getText(),
                            TDuracion.getText(),
                            TObservaciones.getText()
                        }
                );
                mensajeFinal = mensajeFinal + "\nDetalle: " + resultadoDetalle[1];
            }

            JOptionPane.showMessageDialog(this, mensajeFinal);
            cnx.entablar(todo, TDetallesRecetas);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, "Revise los datos: el número debe ser entero, la fecha como 2026-12-31 10:30:00 y la vigencia como 2026-12-31");
        }
    }//GEN-LAST:event_BActualizarActionPerformed

    private void BBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BBorrarActionPerformed
        try {
            int numeroReceta = Integer.parseInt(TNumero.getText());

            if (CBClaveMedicamento.getSelectedIndex() != -1) {
                // Hay un medicamento seleccionado: se borra solo ese detalle
                int respuesta = JOptionPane.showConfirmDialog(this,
                        "¿Eliminar este medicamento de la receta?", "Confirmar", JOptionPane.YES_NO_OPTION);
                if (respuesta == JOptionPane.YES_OPTION) {
                    Object[] resultado = cnx.ejecutarCRUD(
                            "gestionar_detalle_receta",
                            new Object[]{
                                "DELETE",
                                CBClaveMedicamento.getSelectedItem().toString(),
                                numeroReceta,
                                null,
                                null,
                                null,
                                null
                            }
                    );
                    JOptionPane.showMessageDialog(this, "Detalle: " + resultado[1]);
                }
            } else {
                // No hay medicamento: se borra la receta completa
                int respuesta = JOptionPane.showConfirmDialog(this,
                        "¿Eliminar la receta completa?", "Confirmar", JOptionPane.YES_NO_OPTION);
                if (respuesta == JOptionPane.YES_OPTION) {
                    Object[] resultado = cnx.ejecutarCRUD(
                            "gestionar_receta",
                            new Object[]{
                                "DELETE",
                                numeroReceta,
                                null,
                                null,
                                null,
                                null
                            }
                    );
                    JOptionPane.showMessageDialog(this, "Receta: " + resultado[1]);
                }
            }
            cnx.entablar(todo, TDetallesRecetas);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Escriba un número de receta válido");
        }
    }//GEN-LAST:event_BBorrarActionPerformed

